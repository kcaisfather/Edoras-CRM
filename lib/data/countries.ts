const OBSERVERS: Row[] = [
  ["PS", "Filistin", "Palestine", "Filistin Devleti"],
  ["VA", "Vatikan", "Holy See", "Vatican"],
];

const toCountry = (un: Country["un"]) => ([code, name, ...aliases]: Row): Country =>
  Object.freeze({ code, name, un, ...(aliases.length ? { aliases: Object.freeze(aliases) } : {}) });

const byName = (a: Country, b: Country) => collator.compare(a.name, b.name);

export const COUNTRIES: readonly Country[] = Object.freeze([
  Object.freeze<Country>({
    name: DEFAULT_COUNTRY,
    code: "TR",
    un: "member",
    aliases: Object.freeze(["Turkey", "Turkiye", "Türkiye Cumhuriyeti", "TUR"]),
  }),
  ...MEMBERS.map(toCountry("member")).sort(byName),
  ...OBSERVERS.map(toCountry("observer")).sort(byName),
  // Türkiye'nin tanıdığı BM dışı ülkeler (eski kayıtlar da bu adlarla girilmiş).
  Object.freeze<Country>({
    name: "Kıbrıs (KKTC)",
    code: null,
    un: "other",
    aliases: Object.freeze(["KKTC", "Kuzey Kıbrıs", "Kuzey Kıbrıs Türk Cumhuriyeti", "Northern Cyprus"]),
  }),
  Object.freeze<Country>({ name: "Kosova", code: "XK", un: "other", aliases: Object.freeze(["Kosovo"]) }),
]);

/** Ülke adları, `COUNTRIES` sırasıyla (Türkiye başta). */
export const COUNTRY_NAMES: readonly string[] = Object.freeze(COUNTRIES.map((c) => c.name));
